from bam_masterdata.metadata.definitions import ObjectTypeDef, PropertyTypeAssignment
from bam_masterdata.metadata.entities import ObjectType

# Base hierarchy of the v1 datamodel:
#
#   Root
#   ├── Activity
#   │   ├── Experiment   (see `activities.py`)
#   │   └── Computation  (see `activities.py`)
#   └── Entity
#
# Every child inherits the properties of its parent and adds its own intrinsic properties.


class Root(ObjectType):
    defs = ObjectTypeDef(
        code="ROOT",
        description="""Root of the masterdata hierarchy//Wurzel der Masterdaten-Hierarchie""",
        generated_code_prefix="ROOT",
    )

    # TODO: confirm the intrinsic properties of Root on the Miro board
    name = PropertyTypeAssignment(
        code="$NAME",
        data_type="VARCHAR",
        property_label="Name",
        description="""Name""",
        mandatory=False,
        section="General Information",
    )


class Activity(Root):
    # v0 equivalent: EXPERIMENTAL_STEP
    # TODO: store as ontology annotations once `definitions.py` supports external IRIs
    # Ontology: http://purl.obolibrary.org/obo/BFO_0000015, http://www.w3.org/ns/prov#Activity
    defs = ObjectTypeDef(
        code="ACTIVITY",
        description="""Activity//Aktivität""",
        generated_code_prefix="ACT",
        prev_version=["EXPERIMENTAL_STEP"],
    )

    start_date = PropertyTypeAssignment(
        code="START_DATE",
        data_type="TIMESTAMP",
        property_label="Start date",
        description="""Start date//Startdatum""",
        mandatory=False,
        section="General Information",
    )

    end_date = PropertyTypeAssignment(
        code="END_DATE",
        data_type="TIMESTAMP",
        property_label="End date",
        description="""End date//Enddatum""",
        mandatory=False,
        section="General Information",
    )

    # TODO: third property on the Miro board (controlled vocabulary, partially hidden) — add once known

    # TODO: multivalued (several persons) — `PropertyTypeAssignment` has no multivalued flag yet
    operators = PropertyTypeAssignment(
        code="OPERATORS",
        data_type="OBJECT",
        object_code="PERSON",
        property_label="Operators",
        description="""Persons performing the activity//Personen, die die Aktivität durchführen""",
        mandatory=False,
        section="General Information",
    )

    objective = PropertyTypeAssignment(
        code="OBJECTIVE",
        data_type="MULTILINE_VARCHAR",
        property_label="Objective",
        description="""Objective of the activity//Ziel der Aktivität""",
        mandatory=False,
        section="Activity Details",
    )

    activity_sheet = PropertyTypeAssignment(
        code="ACTIVITY_SHEET",
        data_type="XML",
        property_label="Activity sheet",
        description="""Activity sheet (spreadsheet)//Aktivitätsblatt (Tabelle)""",
        mandatory=False,
        section="Activity Details",
    )

    # TODO: multivalued (several entities) — `PropertyTypeAssignment` has no multivalued flag yet
    inputs = PropertyTypeAssignment(
        code="INPUTS",
        data_type="OBJECT",
        object_code="ENTITY",
        property_label="Inputs",
        description="""Entities used by the activity//Von der Aktivität verwendete Entitäten""",
        mandatory=False,
        section="Inputs and Outputs",
    )

    # TODO: multivalued (several entities) — `PropertyTypeAssignment` has no multivalued flag yet
    outputs = PropertyTypeAssignment(
        code="OUTPUTS",
        data_type="OBJECT",
        object_code="ENTITY",
        property_label="Outputs",
        description="""Entities generated by the activity//Von der Aktivität erzeugte Entitäten""",
        mandatory=False,
        section="Inputs and Outputs",
    )


